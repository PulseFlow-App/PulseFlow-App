export type ProsKey = keyof typeof COPY;

export function preferredDateKey(value: string | null | undefined): ProsKey | null {
  if (value === "today" || value === "tomorrow" || value === "flexible") return value;
  if (value === "this_week") return "thisWeek";
  return null;
}

export function preferredTimeKey(value: string | null | undefined): ProsKey | null {
  if (value === "morning" || value === "afternoon" || value === "evening") return value;
  if (value === "any") return "anyTime";
  return null;
}

type ProsCopyRow = { en: string } & Partial<Record<string, string>>;

export function prosT(
  locale: string,
  key: ProsKey,
  params?: Record<string, string | number>,
) {
  const lang = prosLang(locale);
  const row = COPY[key] as ProsCopyRow;
  const fromExtra = PROS_EXTRA_LOCALES[lang]?.[key];
  let text: string = fromExtra || row[lang] || row.en;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function statusKey(status: string): ProsKey {
  switch (status) {
    case "offers_received":
      return "statusOffers";
    case "chosen":
      return "statusChosen";
    case "scheduled":
      return "statusScheduled";
    case "in_progress":
      return "statusProgress";
    case "awaiting_approval":
      return "statusApproval";
    case "completed":
      return "statusCompleted";
    case "cancelled":
      return "statusCancelled";
    default:
      return "statusRequested";
  }
}
